// actually write about their own work. Where the English leans on an idiom that
// does not travel ("where I've been building", "on the record"), the Arabic says
// the thing directly rather than carrying the metaphor across.
//
// Only language-varying text lives here. Numbers, image paths, links, accents and
// technology names stay in the English files so they cannot drift apart, and
// proper nouns stay in Latin script by design.
//
// Two rules here are correctness, not style:
//  - No Arabic sentence may END on a Latin word. The full stop after a Latin run
//    is a neutral character, so it takes the paragraph direction and renders on
//    the wrong side of the name.
//  - Latin names that themselves end in a full stop get wrapped in dir="ltr" at
//    the component, never patched inline here.

